const RPS = { 'حجر': '🪨', 'ورقة': '📄', 'مقص': '✂️' };

const mention = (m) => (m.mentionedJid && m.mentionedJid[0]) || null;

const handler = async (m, { conn, text, command }) => {
  const name = '@' + m.sender.split('@')[0];
  const reply = (t, extra = {}) => conn.sendMessage(m.chat, { text: t, mentions: [m.sender], ...extra }, { quoted: m });

  switch (command) {
    case 'نكتة': case 'joke':
      return reply(`*😂 نكتة*\n\n${pick(JOKES)}`);
    case 'حكمة': case 'اقتباس': case 'quote':
      return reply(`*📜 حكمة*\n\n${pick(QUOTES)}`);
    case 'صراحة': case 'truth':
      return reply(`*🫣 صراحة* — ${name}\n\n${pick(TRUTH)}`);
    case 'جرأة': case 'dare':
      return reply(`*😈 جرأة* — ${name}\n\n${pick(DARE)}`);
    case 'لو_خيروك': case 'wyr':
      return reply(`*🤔 لو خيروك*\n\n${pick(WYR)}`);
    case 'عملة': case 'coin':
      return reply(`*🪙 رميت العملة...*\n\nالنتيجة: *${rnd(2) ? 'صورة 🦅' : 'كتابة ✍️'}*`);
    case 'نرد': case 'dice':
      return reply(`*🎲 رميت النرد...*\n\nطلع: *${rnd(6) + 1}*`);
    case 'كرة': case '8ball':
      if (!text) return reply('*🎱 اسأل سؤال جنب الأمر*\nمثال: .كرة هل هنجح؟');
      return reply(`*🎱 الكرة السحرية*\n\n❓ ${text}\n💬 ${pick(BALL)}`);
    case 'حجر': case 'rps': {
      const choice = (text || '').trim();
      if (!RPS[choice]) return reply('*🎮 اختار: حجر / ورقة / مقص*\nمثال: .حجر ورقة');
      const bot = pick(Object.keys(RPS));
      const win = { 'حجر': 'مقص', 'ورقة': 'حجر', 'مقص': 'ورقة' };
      const result = choice === bot ? 'تعادل 🤝' : (win[choice] === bot ? 'كسبت! 🎉' : 'خسرت! 😎');
      return reply(`*🎮 حجر ورقة مقص*\n\nانت: ${RPS[choice]} ${choice}\nانا: ${RPS[bot]} ${bot}\n\n*${result}*`);
    }
    case 'نسبة_الحب': case 'love': {
      const target = mention(m);
      if (!target) return reply('*💘 منشن الشخص جنب الأمر*\nمثال: .نسبة_الحب @فلان');
      const pct = rnd(101);
      const bar = '❤️'.repeat(Math.round(pct / 10)) + '🤍'.repeat(10 - Math.round(pct / 10));
      return reply(`*💘 نسبة الحب*\n\n${name} ❤️ @${target.split('@')[0]}\n\n${bar}\n*${pct}%*`, { mentions: [m.sender, target] });
    }
    case 'ذكائي': case 'iq':
      return reply(`*🧠 نسبة ذكاء ${name}:* *${60 + rnd(100)}*`);
    case 'جمالي': case 'جمال':
      return reply(`*✨ نسبة جمال ${name}:* *${rnd(101)}%*`);
    case 'مزاج':
      return reply(`*🎭 مزاجك النهاردة:* ${pick(['رايق 😎', 'معصب 😡', 'نعسان 😴', 'سعيد 😄', 'حزين 😢', 'متحمس 🔥', 'جعان 🍕'])}`);
  }
};

handler.usage = ['نكتة', 'حكمة', 'صراحة', 'جرأة', 'لو_خيروك', 'عملة', 'نرد', 'كرة', 'حجر', 'نسبة_الحب', 'ذكائي', 'جمالي', 'مزاج'];
handler.category = 'fun';
handler.command = ['نكتة', 'joke', 'حكمة', 'اقتباس', 'quote', 'صراحة', 'truth', 'جرأة', 'dare', 'لو_خيروك', 'wyr', 'عملة', 'coin', 'نرد', 'dice', 'كرة', '8ball', 'حجر', 'rps', 'نسبة_الحب', 'love', 'ذكائي', 'iq', 'جمالي', 'جمال', 'مزاج'];

import { safe } from '../../system/safe.js';
export default safe(handler, 'fun');
